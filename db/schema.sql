-- Idempotent: it can be run several times (npm run db:setup).
create extension if not exists btree_gist;

create table if not exists businesses (
  id int generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  timezone text not null default 'America/Mexico_City'
);

create table if not exists services (
  id int generated by default as identity primary key,
  business_id int not null references businesses on delete cascade,
  name text not null check (length(trim(name)) > 0),
  duration_min int not null check (duration_min between 5 and 600),
  price numeric(10,2) not null default 0 check (price >= 0)
);

create table if not exists staff (
  id int generated by default as identity primary key,
  business_id int not null references businesses on delete cascade,
  name text not null check (length(trim(name)) > 0)
);

-- One block per day per person.
create table if not exists availability (
  staff_id int not null references staff on delete cascade,
  weekday int not null check (weekday between 0 and 6), -- 0 = domingo
  start_time time not null,
  end_time time not null check (end_time > start_time),
  primary key (staff_id, weekday)
);

create table if not exists appointments (
  id int generated by default as identity primary key,
  business_id int not null references businesses on delete cascade,
  service_id int not null references services,
  staff_id int not null references staff,
  customer_name text not null,
  customer_contact text not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null check (ends_at > starts_at),
  status text not null default 'confirmed' check (status in ('confirmed', 'cancelled')),
  created_at timestamptz not null default now(),
  -- The DB prevents double bookings, whether they come from the form or from the AI.
  constraint no_overlap exclude using gist (staff_id with =, tstzrange(starts_at, ends_at) with &&)
    where (status = 'confirmed')
);

-- Demo data at /demo if the database is empty.
do $$
declare b int; m1 int; m2 int; m3 int;
begin
  if exists (select 1 from businesses) then return; end if;
  insert into businesses (slug, name) values ('demo', 'Restaurante Demo') returning id into b;
  insert into services (business_id, name, duration_min, price) values
    (b, 'Mesa para 2', 90, 0), (b, 'Mesa para 4', 120, 0), (b, 'Mesa para 6', 120, 0);
  -- "Staff" = tables: each one accepts one booking at a time.
  insert into staff (business_id, name) values (b, 'Mesa 1 · Salón') returning id into m1;
  insert into staff (business_id, name) values (b, 'Mesa 2 · Salón') returning id into m2;
  insert into staff (business_id, name) values (b, 'Mesa 3 · Terraza') returning id into m3;
  -- Every day, 13:00 to 23:00.
  insert into availability (staff_id, weekday, start_time, end_time)
    select m, d, '13:00'::time, '23:00'::time from unnest(array[m1, m2, m3]) m, unnest(array[0, 1, 2, 3, 4, 5, 6]) d;
end $$;
